#!/usr/bin/env python3
"""
LaTeX tables (booktabs) of a grid search, one per method, from the summaries
run_grid_search.py wrote. The selected setting of each method (grid_config.yaml,
`selected`) is set in bold, its node defaults (`baseline`) are marked with a dagger.

    python make_tables.py                                   # results/poisson_1.5_4 -> tables/
    python make_tables.py --results results/poisson_2_4 --out tables/poisson_2_4
"""
import argparse
import json
from pathlib import Path

import yaml

from run_grid_search import param_names, criterion, COLLISION_WEIGHT

HERE = Path(__file__).resolve().parent

SYMBOLS = {
    'CCBF_KAPPA':  r'$\kappa$',
    'CCBF_POLE_0': r'$p_0$',
    'CCBF_ALPHA':  r'$\alpha$',
    'DAF_K3':      r'$k_3$',
    'DAF_EPS':     r'$\varepsilon$',
    'DAF_EPS1':    r'$\varepsilon_1$',
    'DAF_EPS2':    r'$\varepsilon_2$',
}
NAMES = {'ccbf': 'Composite CBF', 'daf': 'DAF'}


def matches(row, params):
    return bool(params) and all(abs(float(row[k]) - float(v)) < 1e-9 for k, v in params.items() if k in row)


def cell(text, bold):
    return r'{\boldmath\bfseries ' + text + '}' if bold else text


def pct(x):
    return f"{100 * x:.0f}"


def table(method, rows, method_cfg, run_cfg):
    names = param_names(method_cfg)
    fixed = method_cfg.get('fixed', {}) or {}
    worlds = run_cfg['worlds']
    lo, hi = worlds['poisson_radius']
    n_runs = sorted({r['n'] for r in rows})

    # grid order: first parameter outermost, values ascending
    rows = sorted(rows, key=lambda r: tuple(float(r[n]) for n in names))

    def assign(params):
        return ', '.join(f"${SYMBOLS.get(k, k).strip('$')} = {v:g}$" for k, v in params.items())

    baseline = method_cfg.get('baseline') or {}
    baseline_in_grid = any(matches(r, baseline) for r in rows)
    if baseline_in_grid:
        defaults_txt = ", node defaults marked $^\\dagger$."
    elif baseline:
        defaults_txt = f"; the node defaults ({assign(baseline)}) lie outside this grid."
    else:
        defaults_txt = "."
    caption = (f"{NAMES.get(method, method)}: closed-loop grid search in the 2D simulation, "
               f"{'/'.join(map(str, n_runs))} worlds per setting (Poisson radius "
               f"$\\sim\\mathcal{{U}}[{lo:g}, {hi:g}]$\\,m, pillar radius {worlds['pillar_radius']:g}\\,m)"
               f"{', ' + assign(fixed) if fixed else ''}. "
               f"$J = S - {COLLISION_WEIGHT:g}C$ is the selection criterion (success rate $S$, collision rate "
               f"$C$, in percentage points). "
               f"Success, collision and timeout rates with the 95\\,\\% Wilson interval of the "
               f"success rate; $\\bar t_\\mathrm{{succ}}$ is the mean time of the successful runs, "
               f"$\\bar v$ the mean speed. Selected setting in bold" + defaults_txt)

    head = ' & '.join([SYMBOLS.get(n, n) for n in names] +
                      [r'$J$', r'Succ.\ [\%]', r'95\,\% CI', r'Coll.\ [\%]', r'T/O [\%]',
                       r'$\bar t_\mathrm{succ}$ [s]', r'$\bar v$ [m/s]'])
    lines = [
        f"% Generated by make_tables.py from {method}/summary.json -- requires \\usepackage{{booktabs}}",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        f"\\caption{{{caption}}}",
        f"\\label{{tab:gridsearch_{method}}}",
        r"\begin{tabular}{" + 'r' * len(names) + 'rrcrrrr}',
        r"\toprule",
        head + r" \\",
        r"\midrule",
    ]
    prev_outer = None
    for r in rows:
        if prev_outer is not None and float(r[names[0]]) != prev_outer:
            lines.append(r"\midrule")
        prev_outer = float(r[names[0]])

        bold = matches(r, method_cfg.get('selected'))
        dagger = '^\\dagger' if matches(r, baseline) else ''
        lo_ci, hi_ci = (float(x) for x in r['success_ci95'].split('-'))
        t = f"{r['mean_success_time']:.1f}" if r['mean_success_time'] is not None else '--'
        v = f"{r['mean_speed']:.2f}" if r['mean_speed'] is not None else '--'
        cells = [f"${float(r[n]):g}{dagger if i == 0 else ''}$" for i, n in enumerate(names)]
        crit = 100 * criterion(r['success_rate'], r['collision_rate'])
        cells += [f"${crit:+.0f}$", pct(r['success_rate']), f"[{pct(lo_ci)}, {pct(hi_ci)}]", pct(r['collision_rate']),
                  pct(r['timeout_rate']), t, v]
        lines.append(' & '.join(cell(c, bold) for c in cells) + r' \\')
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description="LaTeX tables of a grid search")
    ap.add_argument('--results', default=str(HERE / 'results' / 'poisson_1.5_4'))
    ap.add_argument('--config', default=str(HERE / 'grid_config.yaml'),
                    help="for the selected/baseline settings")
    ap.add_argument('--out', default=str(HERE / 'tables'))
    args = ap.parse_args()

    cfg = yaml.safe_load(open(args.config))
    results, out = Path(args.results), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for method, method_cfg in cfg['methods'].items():
        summary = results / method / 'summary.json'
        if not summary.exists():
            print(f"  {method}: no summary in {results}")
            continue
        run_cfg = yaml.safe_load(open(results / method / 'grid_config.yaml'))
        # the grid of the run, the selection and defaults of the current config
        method_cfg = dict(run_cfg['method']) | {k: method_cfg.get(k) for k in ('selected', 'baseline')}
        rows = json.loads(summary.read_text())
        path = out / f"gridsearch_{method}.tex"
        path.write_text(table(method, rows, method_cfg, run_cfg))
        print(f"  {method}: {len(rows)} settings -> {path}")


if __name__ == '__main__':
    main()
